<?php

namespace App\Enums;

/**
 * The priority of a backlog item.
 *
 * Proposed by the SRS and still awaiting product owner confirmation, so the
 * values live in one place instead of being scattered across the code.
 */
enum BacklogPriority: string
{
    case Low = 'low';
    case Medium = 'medium';
    case High = 'high';
    case Urgent = 'urgent';

    /**
     * Get the human readable label for the priority.
     */
    public function label(): string
    {
        return match ($this) {
            self::Low => 'Low',
            self::Medium => 'Medium',
            self::High => 'High',
            self::Urgent => 'Urgent',
        };
    }

    /**
     * Get the sort weight, so lists show the most pressing work first.
     */
    public function weight(): int
    {
        return match ($this) {
            self::Low => 1,
            self::Medium => 2,
            self::High => 3,
            self::Urgent => 4,
        };
    }
}
